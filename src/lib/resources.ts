export const RESOURCES: Record<string, Resource> = Object.fromEntries(R.map((r) => [r.table, r]));

export function getResource(table: string): Resource | null {
  return RESOURCES[table] ?? null;
}

export function recordHref(table: string, id: string): string {
  if (table === "pipelines") return `/opportunities/${id}`;
  if (table === "reviews") return `/accountability/reviews/${id}`;
  if (table === "partner_reports") return `/accountability/reports/${id}`;
  if (table === "scenarios") return `/plan/scenarios/${id}`;
  return `/records/${table}/${id}`;
}

export function newRecordHref(table: string, prefill: Record<string, string> = {}): string {
  const qs = new URLSearchParams(prefill).toString();
  return `/records/${table}/new${qs ? `?${qs}` : ""}`;
}

