export type FieldType =
  | "text"
  | "textarea"
  | "number"
  | "money"
  | "percent"
  | "date"
  | "datetime"
  | "boolean"
  | "select"
  | "ref"
  | "tags"
  | "multiselect"
  | "actions"
  | "json"
  | "email"
  | "url";

export type Option = { value: string; label: string };

export type Field = {
  name: string;
  label: string;
  type: FieldType;
  options?: Option[];
  ref?: string;
  required?: boolean;
  help?: string;
  hideOnForm?: boolean;
  readOnly?: boolean;
  default?: string | number | boolean;
  /** Reference fields: a named subset of the referenced records (example: "consulting" = consulting pipeline items only). */
  refSubset?: string;
  /** Form section heading. Fields with the same section are shown together under it, in field order. */
  section?: string;
};

export type Child = { table: string; fk: string; label: string };

export type Resource = {
  table: string;
  singular: string;
  plural: string;
  titleField: string;
  listHref: string;
  fields: Field[];
  columns: string[];
  order: [string, boolean];
  empty: string;
  children?: Child[];
  noCreate?: boolean;
  noDelete?: boolean;
  noEdit?: boolean;
};

const o = (...vals: string[]): Option[] =>
  vals.map((v) => ({ value: v, label: (v.charAt(0).toUpperCase() + v.slice(1)).replace(/_/g, " ") }));

